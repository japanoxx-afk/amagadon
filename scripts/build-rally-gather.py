"""Share the existing HD ore-rally simulation hooks with the original renderer."""
from pathlib import Path
import sys,re,struct
ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT/'.tools'))
from keystone import Ks,KS_ARCH_X86,KS_MODE_32
from capstone import *
from capstone.x86 import *
BASE=0x20000000
source=(ROOT/'scripts/probe-resolution.py').read_text(encoding='utf-8')
ks=Ks(KS_ARCH_X86,KS_MODE_32);cs=Cs(CS_ARCH_X86,CS_MODE_32);cs.detail=True
payload=bytearray(2048);absolute=[];relative=[];sites=[]
for site,offset,before in [(0x408730,512,'89869c130000'),(0x430e49,768,'bf93f7ffff')]:
    match=re.search(r'hook\(0x%06x,bytes.fromhex\(.*?\),f"""(.*?)"""'%site,source,re.S)
    assert match
    assembly=match.group(1).replace('{rally_targets}',str(BASE+4096))
    code=bytes(ks.asm(assembly,BASE+offset)[0]);assert offset+len(code)<2048
    payload[offset:offset+len(code)]=code
    for i in cs.disasm(code,BASE+offset):
        for op in i.operands:
            if op.type==X86_OP_MEM and BASE<=op.mem.disp<BASE+24576:absolute.append(i.address-BASE+i.disp_offset)
            if op.type==X86_OP_IMM:
                branch=i.group(CS_GRP_JUMP) or i.group(CS_GRP_CALL)
                if branch and not BASE<=op.imm<BASE+24576:relative.append(i.address-BASE+i.imm_offset)
                elif not branch and BASE<=op.imm<BASE+24576:absolute.append(i.address-BASE+i.imm_offset)
    sites.append((site,offset,len(bytes.fromhex(before))))
body='// Generated by scripts/build-rally-gather.py; shared HD simulation logic.\nusing System;using System.Collections.Generic;\nnamespace Amagadon {public static partial class RallySpawn {\n static void AddGather(int cave,byte[] payload,Dictionary<int,byte[]> result) {\n  byte[] gather=NetworkGuard.Hex("HEX");int delta=unchecked(cave-0x20000000);\n  foreach(int offset in new[]{ABS})Buffer.BlockCopy(BitConverter.GetBytes(unchecked(BitConverter.ToInt32(gather,offset)+delta)),0,gather,offset,4);\n  foreach(int offset in new[]{REL})Buffer.BlockCopy(BitConverter.GetBytes(unchecked(BitConverter.ToInt32(gather,offset)-delta)),0,gather,offset,4);\n  Buffer.BlockCopy(gather,512,payload,512,1536);\nSITES\n }\n}}\n'
body=body.replace('HEX',payload.hex()).replace('ABS',','.join(map(str,absolute))).replace('REL',','.join(map(str,relative)))
lines=[]
for site,offset,n in sites:
    lines.append('  {byte[] jump=new byte[%d];for(int i=0;i<jump.Length;i++)jump[i]=0x90;jump[0]=0xe9;Buffer.BlockCopy(BitConverter.GetBytes(cave+%d-0x%x),0,jump,1,4);result.Add(0x%x,jump);}'%(n,offset,site+5,site))
body=body.replace('SITES','\n'.join(lines))
(ROOT/'src/RallyGather.cs').write_text(body,encoding='utf-8')
print('Generated shared ore-rally hooks:',sites)
